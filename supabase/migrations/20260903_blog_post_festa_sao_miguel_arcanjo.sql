<h2>A festa mais tradicional de São Miguel do Gostoso</h2>

<p>O nome da cidade não é coincidência. Em 29 de setembro de 1884, dia dedicado a São Miguel Arcanjo no calendário católico, o frei João do Amor Divino instalou um cruzeiro e celebrou a primeira missa no vilarejo que viria a se chamar Gostoso. Pouco depois, um morador chamado Miguel Felix Martins, gravemente doente, prometeu ao santo que construiria uma capela em sua homenagem caso se curasse. Ele se recuperou, cumpriu a promessa, e a imagem de São Miguel Arcanjo virou padroeiro oficial do lugarejo. Com o tempo, a população passou a chamar a cidade de "São Miguel" somado a "Gostoso", nome que ficou até hoje.</p>

<p>É por isso que a festa de setembro não é só mais um evento de alta temporada. Ela celebra o próprio nascimento da cidade, e por isso mobiliza igreja, prefeitura e comércio local num dos períodos de maior movimento do ano, ao lado da temporada de vento forte que atrai os kitesurfistas.</p>

<h2>Patrimônio Cultural e Imaterial do Rio Grande do Norte</h2>

<p>Em 2025, a Festa de São Miguel Arcanjo ganhou reconhecimento oficial: a governadora Fátima Bezerra sancionou a Lei Estadual nº 12.103/2025, declarando a celebração Patrimônio Religioso, Cultural, Turístico e Imaterial do Estado. <a href="https://site.saomigueldogostoso.rn.gov.br/post/festa-de-sao-miguel-arcanjo-e-reconhecida-como-patrimonio-cultural-e-imaterial-do-rn" target="_blank" rel="noopener noreferrer">A Prefeitura de São Miguel do Gostoso detalha esse reconhecimento nesta publicação oficial</a>, que explica o peso da festa na identidade religiosa do município e o tanto de gente que ela traz pra cidade todos os anos.</p>

<p>Isso não muda o clima de festa popular na areia da Xêpa, mas ajuda a explicar por que a programação cresce edição após edição e por que vale reservar hospedagem com antecedência se você vem de fora.</p>

