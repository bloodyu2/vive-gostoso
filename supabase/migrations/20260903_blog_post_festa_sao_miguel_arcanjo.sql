<h2>Onde vai acontecer: Praia da Xêpa</h2>

<p>A Praia da Xêpa é a praia mais central de São Miguel do Gostoso, com areia branca e mar calmo, sem ondas fortes. É também onde fica a maior concentração de bares e restaurantes da cidade, na rua de acesso que leva o mesmo nome da praia, a poucos passos da Igreja de São Miguel Arcanjo, a mesma erguida pela promessa que deu origem à festa. Por já ter infraestrutura de quadras esportivas e espaço aberto, a Xêpa é o palco natural das principais celebrações públicas da cidade, incluindo a virada de ano.</p>

